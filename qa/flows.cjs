const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('/Users/Baike_1/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = process.env.WEATHER_QA_URL || 'http://127.0.0.1:4191/weather-v1/';
const output = path.join(__dirname, 'screenshots');
fs.mkdirSync(output, { recursive: true });
const checks = [], errors = [];
const check = (name, result) => { assert.ok(result, name); checks.push(name); console.log(JSON.stringify({ pass: name })); };
async function main() {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  try {
    const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' });
    const page = await ctx.newPage();
    page.on('pageerror', e => errors.push(e.message));
    const shot = async name => { await page.waitForTimeout(450); await page.screenshot({ path: path.join(output, name + '.png') }); };
    await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 25000 });
    await page.getByRole('button', { name: '选择我的地点', exact: true }).waitFor();
    check('Default language is Simplified Chinese', await page.locator('html').getAttribute('lang') === 'zh-CN');
    await shot('01-welcome-zh');
    await page.getByRole('button', { name: '选择我的地点', exact: true }).click();
    await shot('02-location');
    await page.getByRole('button', { name: 'Austin Texas', exact: false }).first().click();
    check('City selection does not prematurely navigate', page.url().includes('/location'));
    await page.getByRole('button', { name: '使用 Austin', exact: true }).click();
    await page.waitForFunction(() => { const d=JSON.parse(localStorage.getItem('weather-personal-v1')||'null'); return d?.snapshots?.austin; }, { timeout: 40000 });
    const d = await page.evaluate(() => JSON.parse(localStorage.getItem('weather-personal-v1')));
    check('Weather uses a labeled live snapshot', d.snapshots.austin.mode === 'live');
    await shot('03-home-zh');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: 'English', exact: true }).click();
    check('Settings changes language to English', await page.getByRole('heading', { name: 'Settings', exact: true }).count() === 1);
    await shot('04-settings-en');
    await page.getByRole('button', { name: '简体中文', exact: true }).click();
    await page.getByRole('button', { name: '天气', exact: true }).click();
    await page.getByRole('button', { name: '72 小时', exact: true }).click();
    await shot('05-forecast');
    await page.getByRole('button', { name: '三天概览', exact: true }).click();
    await shot('06-forecast-days');
    await page.getByRole('button', { name: '返回', exact: true }).click();
    await page.locator('.ootd-preview').click();
    await page.getByRole('button', { name: '偏冷', exact: true }).click();
    await shot('07-outfit');
    await page.getByRole('button', { name: '返回', exact: true }).click();
    await page.locator('.ootd-preview').click();
    check('OOTD feedback survives reopening', await page.getByRole('button', { name: '偏冷', exact: true }).getAttribute('aria-pressed') === 'true');
    await page.getByRole('button', { name: '返回', exact: true }).click();
    await page.getByRole('button', { name: '计划', exact: true }).click();
    await shot('08-plan-empty');
    await page.getByRole('button', { name: '添加跑步计划', exact: true }).last().click();
    await shot('09-editor');
    await page.getByRole('button', { name: '保存并检查天气', exact: true }).click();
    await page.getByRole('heading', { name: '天气判断', exact: true }).waitFor();
    await page.waitForTimeout(1000);
    await shot('10-analysis');
    const start = await page.evaluate(() => JSON.parse(localStorage.getItem('weather-personal-v1')).plans.find(p=>p.status==='scheduled'));
    check('Plan stores its own location and absolute start time', start.location.id === 'austin' && Number.isFinite(start.startAt));
    if(await page.getByRole('button',{name:'保留原计划',exact:true}).count()) await page.getByRole('button',{name:'保留原计划',exact:true}).click();
    else if(await page.getByRole('button',{name:'仍按原时间',exact:true}).count()) await page.getByRole('button',{name:'仍按原时间',exact:true}).click();
    else await page.getByRole('button',{name:'返回',exact:true}).click();
    await shot('11-plan-saved');
    await page.getByRole('button', { name: '天气', exact: true }).click();
    await page.locator('.location-control').click();
    await page.getByRole('button',{name:'Seattle Washington',exact:false}).click();
    await page.getByRole('button',{name:'使用 Seattle',exact:true}).click();
    const after = await page.evaluate(() => JSON.parse(localStorage.getItem('weather-personal-v1')));
    check('Browsing a different city keeps the plan location/time', after.location.id === 'seattle' && after.plans.find(p=>p.id===start.id).location.id==='austin' && after.plans.find(p=>p.id===start.id).startAt===start.startAt);
    await page.getByRole('button',{name:'设置',exact:true}).click();
    await page.getByRole('button',{name:'English',exact:true}).click();
    const en = await page.evaluate(() => JSON.parse(localStorage.getItem('weather-personal-v1')));
    check('Language switching preserves units and absolute time', en.units === after.units && en.plans[0].startAt === after.plans[0].startAt);
    await page.getByRole('button',{name:'简体中文',exact:true}).click();
    await page.getByRole('button',{name:/独立情景演练/}).click();
    await page.getByRole('button',{name:/降雨/}).click();
    await shot('12-rain-scenario');
    check('Rain uses closed droplet paths', await page.locator('.front-drops .drop path').first().getAttribute('d').then(d=>d.endsWith('Z')));
    const beforeMotion = await page.locator('.front-drops .drop').nth(3).evaluate(e=>e.getBoundingClientRect().y);
    await page.waitForTimeout(300);
    const afterMotion = await page.locator('.front-drops .drop').nth(3).evaluate(e=>e.getBoundingClientRect().y);
    check('Droplet animation moves in the rendered app', beforeMotion!==afterMotion);
    await page.getByRole('button',{name:/回放一次雷暴变化/}).click();
    await shot('13-storm-recheck');
    check('Scenario replay updates the actual analysis input', await page.locator('.scenario-hero h2').innerText()==='雷暴');
    const scenarioData = await page.evaluate(() => JSON.parse(localStorage.getItem('weather-personal-v1')));
    check('Scenario playback preserves the real plan', scenarioData.plans[0].startAt === start.startAt);
    await page.emulateMedia({reducedMotion:'reduce'});
    check('Reduced motion disables rain/flash', await page.locator('.drop-layer').first().evaluate(e=>getComputedStyle(e).display)==='none');
    await page.emulateMedia({reducedMotion:'no-preference'});
    await page.getByRole('button',{name:/结束演练/}).click();
    for(const size of [{width:320,height:568},{width:375,height:812},{width:844,height:390}]){
      await page.setViewportSize(size);await page.waitForTimeout(350);
      const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:innerHeight,nav:document.querySelector('.glass-nav').getBoundingClientRect().toJSON()}));
      check(`Navigation remains in viewport ${size.width}x${size.height}`,layout.nav.top>=0&&layout.nav.bottom<=layout.height&&layout.scrollWidth<=layout.width);
      await shot(`adapt-${size.width}x${size.height}`);
    }
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'设置',exact:true}).click();await shot('14-settings-zh');
    await page.getByRole('button',{name:/数据来源与判断规则/}).click();await shot('15-sources');
    await page.getByRole('button',{name:'返回',exact:true}).click();
    await page.getByRole('button',{name:/专业功能价格意向/}).click();await page.getByRole('button',{name:'这个价格，我愿意试用',exact:true}).click();await shot('16-pricing');
    check('Price intent records an experiment, not a charge',await page.evaluate(()=>JSON.parse(localStorage.getItem('weather-personal-v1')).events.some(e=>e.name==='pricing_intent'&&e.properties.paid===false)));
    check('No runtime page errors',errors.length===0);
    fs.writeFileSync(path.join(__dirname,'browser-acceptance.json'),JSON.stringify({base,checks,errors,liveSource:d.snapshots.austin.status,at:new Date().toISOString()},null,2));
    console.log(JSON.stringify({complete:true,checks:checks.length,errors}));
  }finally{await browser.close();}
}
main().catch(e=>{console.error(e.stack);fs.writeFileSync(path.join(__dirname,'browser-acceptance.json'),JSON.stringify({base,checks,errors,failure:e.message},null,2));process.exitCode=1;});
